import { buildGraph, relation, focusSet, oldestAncestor, ancestorCount, wouldCreateCycle, findDuplicates, generationLevels } from "../src/core/relations.ts";
import { SAMPLE } from "../src/core/sample.ts";
const g = buildGraph(SAMPLE);
let fail = 0;
const eq = (label: string, got: unknown, want: unknown) => {
  const ok = JSON.stringify(got) === JSON.stringify(want);
  if (!ok) fail++;
  console.log(ok ? "ok  " : "FAIL", label, ok ? "" : `got=${JSON.stringify(got)} want=${JSON.stringify(want)}`);
};
const R = (t: string) => relation(g, "me", t);
eq("father", R("dad"), "বাবা"); eq("mother", R("mom"), "মা");
eq("paternal grandfather", R("pgf"), "দাদা"); eq("paternal grandmother", R("pgm"), "দাদি");
eq("maternal grandfather", R("mgf"), "নানা"); eq("maternal grandmother", R("mgm"), "নানি");
eq("great-grandfather", R("pggf"), "পরদাদা");
eq("sister", R("sis"), "বোন"); eq("wife", R("wife"), "স্ত্রী");
eq("son", R("son"), "ছেলে"); eq("daughter", R("dau"), "মেয়ে");
eq("chacha", R("uncle"), "চাচা"); eq("chachi", R("auntw"), "চাচি"); eq("fufu", R("fufu"), "ফুফু");
eq("mama", R("mama"), "মামা"); eq("khala", R("khala"), "খালা");
eq("chachato bhai", R("cous"), "চাচাতো ভাই"); eq("khalato bon", R("khcous"), "খালাতো বোন");
eq("from son: dada", relation(g, "son", "dad"), "দাদা"); eq("from son: nana(mother's father)", relation(g, "son", "wife"), "মা");
eq("from sis: brother", relation(g, "sis", "me"), "ভাই");
eq("from dad: nephew-like (sis's child none) son=নাতি", relation(g, "dad", "son"), "নাতি");
eq("from wife: father-in-law", relation(g, "wife", "dad"), "শ্বশুর");
eq("from cous: ego = চাচাতো ভাই", relation(g, "cous", "me"), "চাচাতো ভাই");
eq("from khcous: ego = খালাতো ভাই", relation(g, "khcous", "me"), "খালাতো ভাই");
eq("oldest", oldestAncestor(g, "me"), { id: "pggf", generations: 3 });
eq("ancestor count", ancestorCount(g, "me"), 7);
eq("cycle blocked", wouldCreateCycle(g, "son", "pggf"), true);
eq("no false cycle", wouldCreateCycle(g, "dad", "cous"), false);
eq("focus parents", focusSet(g, "me").parents, ["dad", "mom"]);
eq("focus gps", focusSet(g, "me").grandparents, ["pgf", "pgm", "mgf", "mgm"]);
eq("focus siblings", focusSet(g, "me").siblings, ["sis"]);
eq("levels[2]", generationLevels(g, "me", 3)[2], ["pgf", "pgm", "mgf", "mgm"]);
eq("duplicates", findDuplicates([{ id: "1", name: "Karim Ali", sex: "male", birthYear: 1950 }, { id: "2", name: " karim  ali", sex: "male" }]), [["1", "2"]]);
console.log(fail ? `${fail} FAILED` : "ALL PASSED");
process.exit(fail ? 1 : 0);
